#!/usr/bin/env python3
"""Clean the source CSV and generate the Prolog analytical base."""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any


FIELDS = [
    "Name", "Platform", "Year_of_Release", "Genre", "Publisher",
    "Global_Sales", "Critic_Score", "Critic_Count", "User_Score", "User_Count",
]
SOURCE_FIELDS = [
    "Name", "Platform", "Year_of_Release", "Genre", "Publisher",
    "NA_Sales", "EU_Sales", "JP_Sales", "Other_Sales", "Global_Sales",
    "Critic_Score", "Critic_Count", "User_Score", "User_Count",
    "Developer", "Rating",
]
MISSING = {"", "n/a", "na", "tbd", "unknown", "null"}


def parse_value(raw: str, kind: str) -> tuple[Any, str]:
    """Return (value, diagnostic), keeping missing and invalid distinct."""
    value = raw.strip()
    if value.lower() in MISSING:
        return None, "missing"
    try:
        parsed = float(value) if kind in {"float", "int"} else value
    except ValueError:
        return None, "invalid"
    if kind == "int":
        if not math.isfinite(parsed) or not parsed.is_integer():
            return None, "invalid"
        return int(parsed), "valid"
    if kind == "float":
        return (parsed, "valid") if math.isfinite(parsed) else (None, "invalid")
    return parsed, "valid"


def clean_row(row: dict[str, str], problems: Counter[str]) -> dict[str, Any] | None:
    name = row["Name"].strip()
    if not name:
        problems["removed_missing_name"] += 1
        return None
    result: dict[str, Any] = {"Name": name}
    kinds = {
        "Year_of_Release": "int", "Global_Sales": "float",
        "Critic_Score": "float", "Critic_Count": "int",
        "User_Score": "float", "User_Count": "int",
    }
    for field in FIELDS[1:]:
        kind = kinds.get(field, "text")
        parsed, status = parse_value(row[field], kind)
        if status == "missing":
            problems[f"missing_{field}"] += 1
        elif status == "invalid":
            problems[f"invalid_{field}"] += 1
        result[field] = parsed

    ranges = (
        ("Critic_Score", 0, 100),
        ("User_Score", 0, 10),
        ("Global_Sales", 0, None),
        ("Critic_Count", 0, None),
        ("User_Count", 0, None),
    )
    for field, lower, upper in ranges:
        value = result[field]
        if value is not None and (value < lower or (upper is not None and value > upper)):
            problems[f"invalid_{field}_range"] += 1
            result[field] = None
    return result


def atom(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def term(value: Any) -> str:
    if value is None:
        return "desconhecido"
    if isinstance(value, str):
        return atom(value)
    return repr(value) if isinstance(value, float) else str(value)


def write_facts(rows: list[dict[str, Any]], output: Path) -> None:
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(":- dynamic jogo/10.\n")
        stream.write("% Generated by etl.py; missing values are desconhecido.\n")
        for row in rows:
            stream.write(f"jogo({', '.join(term(row[field]) for field in FIELDS)}).\n")


def identity(row: dict[str, Any]) -> tuple[Any, Any, Any]:
    return row["Name"], row["Platform"], row["Year_of_Release"]


def selected_values(row: dict[str, Any]) -> tuple[Any, ...]:
    return tuple(row[field] for field in FIELDS)


def run(
    input_path: Path,
    output_path: Path,
    summary_path: Path,
    conflicts_path: Path,
) -> dict[str, Any]:
    problems: Counter[str] = Counter()
    cleaned: list[dict[str, Any]] = []
    raw_by_identity: defaultdict[tuple[Any, Any, Any], list[dict[str, str]]] = defaultdict(list)
    with input_path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != SOURCE_FIELDS:
            raise ValueError(f"Unexpected CSV columns: {reader.fieldnames}")
        records_read = 0
        for raw in reader:
            records_read += 1
            row = clean_row(raw, problems)
            if row is not None:
                cleaned.append(row)
                raw_by_identity[identity(row)].append(dict(raw))

    by_identity: defaultdict[tuple[Any, Any, Any], list[dict[str, Any]]] = defaultdict(list)
    for row in cleaned:
        by_identity[identity(row)].append(row)
    conflict_keys = {
        key for key, rows in by_identity.items()
        if len({selected_values(row) for row in rows}) > 1
    }
    exact_duplicate_removed = 0
    conflict_rows: list[dict[str, Any]] = []
    analytical_rows: list[dict[str, Any]] = []
    for key, rows in by_identity.items():
        if key in conflict_keys:
            conflict_rows.append({
                "identity": list(key),
                "source_rows": raw_by_identity[key],
                "cleaned_rows": rows,
            })
            problems["removed_conflict_rows"] += len(rows)
        else:
            analytical_rows.append(rows[0])
            exact_duplicate_removed += len(rows) - 1
    problems["removed_exact_duplicate_rows"] += exact_duplicate_removed

    write_facts(analytical_rows, output_path)
    conflicts_path.write_text(
        json.dumps(conflict_rows, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    removed_missing = problems["removed_missing_name"]
    removed_exact = exact_duplicate_removed
    removed_conflicts = problems["removed_conflict_rows"]
    summary = {
        "source": str(input_path),
        "records_read": records_read,
        "records_kept": len(analytical_rows),
        "records_removed": removed_missing + removed_exact + removed_conflicts,
        "removed_by_reason": {
            "missing_name": removed_missing,
            "exact_duplicate_selected_fields": removed_exact,
            "conflicting_identity": removed_conflicts,
        },
        "exact_duplicate_rows_removed": removed_exact,
        "conflicting_identities": {
            "|".join(map(str, item["identity"])): len(item["cleaned_rows"])
            for item in conflict_rows
        },
        "problem_counts": dict(sorted(problems.items())),
        "missing_by_field": {
            field: sum(row[field] is None for row in analytical_rows) for field in FIELDS
        },
        "year_values": sorted({
            row["Year_of_Release"] for row in analytical_rows
            if isinstance(row["Year_of_Release"], int)
        }),
    }
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=Path("Video_Games_Sales_as_at_22_Dec_2016.csv"))
    parser.add_argument("--facts", type=Path, default=Path("jogos.pl"))
    parser.add_argument("--summary", type=Path, default=Path("limpeza.json"))
    parser.add_argument("--conflicts", type=Path, default=Path("conflitos.json"))
    args = parser.parse_args()
    print(json.dumps(run(args.input, args.facts, args.summary, args.conflicts),
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
